"""
Abstract base class interface for Vision Language Models (VLMs).
Guarantees uniform API for API-based and local HuggingFace VLMs.
"""

import gc
import logging
from abc import ABC, abstractmethod
from typing import Any

from PIL import Image

logger = logging.getLogger("vlm_benchmark")


class BaseModel(ABC):
    """
    Abstract Base Class representing a Vision Language Model wrapper.
    Ensures standard methods for lifecycle and prediction.
    """

    def __init__(
        self,
        model_id: str,
        device: str = "cuda",
        precision: str = "bf16",
        quantization: str = "4bit",
        **kwargs,
    ):
        """
        Initializes common VLM configurations.

        Args:
            model_id: HuggingFace model ID or API name (e.g., 'gpt-4o').
            device: 'cuda' or 'cpu'.
            precision: FP precision to use ('fp16', 'bf16', 'float32').
            quantization: Quantization method ('none', '4bit', '8bit').
            **kwargs: Extra model-specific kwargs.
        """
        self.model_id = model_id
        self.device = device
        self.precision = precision
        self.quantization = quantization
        self.kwargs = kwargs

        # Model & Processor references
        self.model: Any = None
        self.processor: Any = None

        # Benchmarking parameters
        self.load_time: float = 0.0
        self.is_loaded: bool = False

        logger.info(
            f"Initialized model wrapper for {model_id} on {device} ({precision}, {quantization})"
        )

    @abstractmethod
    def load_model(self) -> None:
        """
        Loads the model and processor/tokenizer into memory.
        Must set self.is_loaded = True, measure and set self.load_time.
        """

    @abstractmethod
    def generate(self, image: Image.Image, prompt: str) -> str:
        """
        Runs VLM inference with the exact prompt and PIL Image.

        Args:
            image: PIL Image object.
            prompt: Text prompt string.

        Returns:
            The raw text output generated by the model.
        """

    def cleanup(self) -> None:
        """
        Unloads the model and processor from memory.
        Performs thorough garbage collection and flushes the PyTorch CUDA cache.
        """
        logger.info(f"Unloading model {self.model_id}...")
        self.model = None
        self.processor = None
        self.is_loaded = False

        # Force garbage collection
        gc.collect()

        # Clear CUDA memory if available
        try:
            import torch

            if torch.cuda.is_available():
                torch.cuda.empty_cache()
                torch.cuda.synchronize()
                logger.info("Cleared PyTorch CUDA cache.")
        except ImportError:
            pass

        logger.info(f"Model {self.model_id} successfully unloaded.")
